namespace WidgetRail.OverlayFrontend.WinUI.Validation;

internal sealed partial class WidgetStylesValidationPage
{
    // Generated two-frame red/blue images, 200 ms per frame, looping forever.
    // PNG and lossless WebP generated with Pillow 13; independently reopened as
    // two-frame files. These bytes contain no user media and require no network.
    private async Task ImageFormatsAsync(string output)
    {
        var formats = new[]
        {
            (Name: "gif", Bytes: TwoFrameGif()),
            (Name: "apng", Bytes: Convert.FromBase64String("iVBORw0KGgoAAAANSUhEUgAAAAIAAAACCAYAAABytg0kAAAACGFjVEwAAAACAAAAAPONk3AAAAAaZmNUTAAAAAAAAAACAAAAAgAAAAAAAAAAAAEABQAA4wibPQAAABVJREFUeJxj/M/A8J+BgYGBCUSAMAAfFwICAkezFAAAABpmY1RMAAAAAQAAAAIAAAACAAAAAAAAAAAAAQAFAAB4e3HpAAAAGWZkQVQAAAACeJxjZGD4/5+BgYGBCUSAMAAdGQICRW6eVwAAAABJRU5ErkJggg==")),
            (Name: "webp", Bytes: Convert.FromBase64String("UklGRoQAAABXRUJQVlA4WAoAAAACAAAAAQAAAQAAQU5JTQYAAAAAAAAAAABBTk1GKAAAAAAAAAAAAAEAAAEAAMgAAAJWUDhMDwAAAC8BQAAABxD9j/4HIqL/AQBBTk1GKAAAAAAAAAAAAAEAAAEAAMgAAABWUDhMDwAAAC8BQAAABxDR//4HIqL/AQA="))
        };
        var results = new List<object>();
        Exception? failure = null;
        try
        {
            foreach (var format in formats)
            {
                var artwork = new WidgetArtworkView { Width = 96, Height = 96 };
                artwork.ApplyStyle(new(Stretch.Fill));
                host.Children.Add(artwork);
                BitmapImage? bitmap = null;
                var colors = new HashSet<string>();
                string? decodeError = null;
                bool animated = false, playing = false;
                try
                {
                    using var deadline = new CancellationTokenSource(TimeSpan.FromSeconds(20));
                    var decoded = await NativeArtworkDecoder.DecodeAsync(new(format.Bytes, IsPublicMedia: true),
                        new(96, 96), ImageFit.Fill, deadline.Token, autoPlay: false);
                    bitmap = decoded?.Image ?? throw new InvalidOperationException("No decoded image.");
                    artwork.Source = bitmap;
                    await Wait(() => artwork.IsLoaded && artwork.ActualWidth > 0);
                    animated = bitmap.IsAnimatedBitmap;
                    bitmap.Play();
                    for (var sample = 0; sample < 12; sample++)
                    {
                        await Task.Delay(110, deadline.Token);
                        colors.Add(await CenterColor(artwork));
                    }
                    playing = bitmap.IsPlaying;
                    if (animated)
                    {
                        Check(playing && colors.Contains("0000FFFF") && colors.Contains("FF0000FF"),
                            format.Name + " exposes actual red and blue decoded frames through public artwork");
                        bitmap.Stop();
                        await Task.Delay(250, deadline.Token);
                        var stopped = await CenterColor(artwork);
                        await Task.Delay(450, deadline.Token);
                        Check(!bitmap.IsPlaying && await CenterColor(artwork) == stopped,
                            format.Name + " stops changing pixels when playback is suspended");
                    }
                    else Check(colors.Contains("0000FFFF") || colors.Contains("FF0000FF"),
                        format.Name + " has a visible static fallback on this Windows decoder");
                }
                catch (System.Runtime.InteropServices.COMException error)
                {
                    // Report unsupported codecs explicitly; do not mislabel an
                    // unavailable decoder as a successful animation test.
                    decodeError = $"{error.GetType().Name}: 0x{error.HResult:X8}";
                }
                finally
                {
                    bitmap?.Stop(); artwork.Source = null; host.Children.Remove(artwork);
                    results.Add(new { format = format.Name, animated, playing, colors, decodeError });
                }
                if (format.Name == "gif")
                    Check(animated && playing && decodeError is null, "Public GIF animation remains supported");
            }
        }
        catch (Exception error) { failure = error; }
        finally
        {
            Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(output))!);
            await File.WriteAllTextAsync(output, JsonSerializer.Serialize(new
            {
                passed = failure is null, checks, formats = results, error = failure?.ToString(),
                scope = "Generated bytes through public artwork admission and production ImageBrush pixels; no network, live Discord payload or video-plane qualification."
            }));
        }
        if (failure is not null) throw failure;
    }
}
