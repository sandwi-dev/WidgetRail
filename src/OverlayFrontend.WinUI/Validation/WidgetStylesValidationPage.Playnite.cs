    private async Task PlayniteProductionLayoutAsync(string path)
    {
        // Generated by PlayniteLibraryNativeLayoutFixtureTests using the actual
        // widget presenter + platform/package WRSS, not a parallel fixture UI.
        using var file = JsonDocument.Parse(await File.ReadAllBytesAsync(path));
        if (file.RootElement.TryGetProperty("navigationFrames", out var navigationFrames))
        { await PlayniteDetailsNavigationAsync(path, navigationFrames); return; }
        if (file.RootElement.TryGetProperty("ranges", out _))
        { await PlayniteIndexedRowsAsync(file.RootElement); return; }
        var snapshot = SnapshotJson.Deserialize(System.Text.Encoding.UTF8.GetBytes(file.RootElement.GetProperty("snapshot").GetRawText()));
        var options = new JsonSerializerOptions { PropertyNameCaseInsensitive = true };
        options.Converters.Add(new JsonStringEnumConverter(JsonNamingPolicy.CamelCase));
        var styles = file.RootElement.GetProperty("renderStyles").Deserialize<Dictionary<string, BridgeNodeRenderStyles>>(options)!;
        var scale = XamlRoot.RasterizationScale;
        App.Window.AppWindow.Resize(new((int)(1160 * scale), (int)(860 * scale)));
        presenter.ApplyAppearance(AppearanceSettings.Default with { Motion = MotionPreference.Reduced }, false);
        presenter.ResolveArtworkAsync = (_, _) => Task.FromResult<WidgetArtworkSource?>(new WidgetEncodedArtwork(WidgetArtworkContentType.Png,
            Convert.FromBase64String("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jq1sAAAAASUVORK5CYII=")));
        presenter.Width = 1000; presenter.Height = 600;
        var descriptor = new BridgeWidgetDescriptor { Id = "playnite.layout", Name = "Production Playnite layout",
            InstanceId = snapshot.WidgetInstanceId, RuntimeGeneration = "production-fixture", PresentationGeneration = "production-fixture",
            Icon = WidgetGlyph.Play, PackageContentDigest = string.Empty };
        presenter.Apply(new(new(descriptor.Id, descriptor.RuntimeGeneration, descriptor.PresentationGeneration, 1,
            descriptor.InstanceId, snapshot.Sequence, snapshot.ActiveInputScopeId), descriptor, snapshot, styles));
        const string prefix = "Widget.playnite-library.details.";
        await Wait(() => Find<WidgetArtworkView>(prefix + "poster") is { Source: BitmapSource { PixelWidth: > 0 } });
        var panel = Find<WidgetModalPanel>("Widget.playnite-library.details")!;
        Check(panel.Background is AcrylicBrush { TintOpacity: .35, TintLuminosityOpacity: .25 } && panel.Opacity == 1,
            "the production modal uses a native acrylic brush without fading its text");
        var acrylic = panel.Background;
        presenter.ApplyAppearance(AppearanceSettings.Default with { Motion = MotionPreference.Reduced }, false);
        Check(ReferenceEquals(acrylic, panel.Background), "unchanged modal styles reuse the acrylic brush");
        presenter.ApplyAppearance(AppearanceSettings.Default with { Motion = MotionPreference.Reduced, Transparency = TransparencyPreference.Reduced }, false);
        await Wait(() => panel.Background is SolidColorBrush { Color.A: 255 });
        Check(panel.Opacity == 1, "reduced transparency preserves opaque modal text and fill");
        presenter.ApplyAppearance(AppearanceSettings.Default with { Motion = MotionPreference.Reduced }, false);
        WidgetViewPresenter.SetHighContrastStyleOverride(true);
        await Wait(() => panel.Background is SolidColorBrush);
        WidgetViewPresenter.SetHighContrastStyleOverride(null);
        await Wait(() => panel.Background is AcrylicBrush);
        var modalAdapter = NativeComputedStyleAdapter.For(panel)!;
        modalAdapter.Update(null);
        Check(panel.Background is not AcrylicBrush, "removing modal styles relinquishes the acrylic brush");
        modalAdapter.Update(styles["playnite-library.details"]);
        Check(panel.Background is AcrylicBrush, "reapplying modal styles restores acrylic");
        var scroll = Find<ScrollViewer>("Widget.playnite-library.details.scroll")!;
        var poster = Find<WidgetArtworkView>(prefix + "poster")!;
        var play = Find<Button>(prefix + "play")!;
        play.Focus(FocusState.Keyboard);
        await Task.Delay(150);
        Check(scroll.HorizontalScrollBarVisibility == ScrollBarVisibility.Disabled && scroll.HorizontalOffset == 0 &&
            scroll.ExtentWidth <= scroll.ViewportWidth + 1, "production Playnite modal keeps finite horizontal measure despite its long description");
        var posterSlot = LayoutInformation.GetLayoutSlot(poster);
        var posterOrigin = Find<Grid>(prefix + "overview-header")!.TransformToVisual(scroll).TransformPoint(new(posterSlot.X, posterSlot.Y));
        Check(posterOrigin.X >= 0 && posterOrigin.X + posterSlot.Width <= scroll.ViewportWidth + 1 && poster.ActualHeight >= 180 && poster.ActualHeight <= 220,
            "production Playnite decoded poster remains inside the modal viewport after focus reveal");
        var tabs = snapshot.Root.Children[1];
        var tabButtons = Walk(tabs).Where(node => node.ActionId?.StartsWith("playnite-library.details.tab.", StringComparison.Ordinal) == true).ToArray();
        Check(tabButtons.Length == 5 && tabButtons.All(node =>
        {
            var button = Find<Button>("Widget." + node.Id)!;
            var origin = button.TransformToVisual(scroll).TransformPoint(new(0, 0));
            return button.ActualWidth > 20 && origin.X >= 0 && origin.X + button.ActualWidth <= scroll.ViewportWidth + 1;
        }), "all five production details navigation options fit the finite modal width");
        var header = Find<Grid>(prefix + "overview-header")!;
        var headerBefore = header.TransformToVisual(presenter).TransformPoint(new(0, 0));
        var playBefore = play.TransformToVisual(presenter).TransformPoint(new(0, 0));
        var firstTab = Find<Button>("Widget." + tabButtons[0].Id)!;
        var tabBefore = firstTab.TransformToVisual(presenter).TransformPoint(new(0, 0));
        var completion = Find<FrameworkElement>(prefix + "completion.action")!;
        var completionBefore = completion.TransformToVisual(presenter).TransformPoint(new(0, 0));
        var sourceOrigin = Find<TextBlock>(prefix + "source")!.TransformToVisual(presenter).TransformPoint(new(0, 0));
        Check(Math.Abs(playBefore.X - sourceOrigin.X) < 2 && Math.Abs(completionBefore.X - sourceOrigin.X) < 2,
            "Play and Completion align with the source label instead of centering within the controls column");
        var description = Find<TextBlock>(prefix + "description")!;
        var descriptionBefore = description.TransformToVisual(presenter).TransformPoint(new(0, 0));
        Check(description.TransformToVisual(scroll).TransformPoint(new(0, 0)).X >= 10,
            "reading text has breathing room inside its focus outline");
        Check(scroll.ScrollableHeight > 64 && scroll.ViewportHeight > 100, "only the lower section has a bounded scrollable viewport");
        // Use the production Description tab as the focus anchor. With no buttons
        // in the description, directional fallback must still reveal its text.
        Find<Button>("Widget." + tabButtons[0].Id)!.Focus(FocusState.Keyboard);
        await Task.Delay(100);
        Check(presenter.MoveFocus(FocusNavigationDirection.Down), "Down from Overview enters the separate reading viewport");
        await Task.Delay(100);
        Check(presenter.MoveFocus(FocusNavigationDirection.Down), "Down inside the reading viewport scrolls its noninteractive content");
        await Wait(() => scroll.VerticalOffset > 1);
        Check(header.TransformToVisual(presenter).TransformPoint(new(0, 0)) == headerBefore &&
            play.TransformToVisual(presenter).TransformPoint(new(0, 0)) == playBefore,
            "artwork and game controls remain stationary while section content scrolls");
        Check(description.TransformToVisual(presenter).TransformPoint(new(0, 0)).Y < descriptionBefore.Y,
            "description text actually moves through the lower viewport");
        Check(firstTab.TransformToVisual(presenter).TransformPoint(new(0, 0)) == tabBefore &&
            completion.TransformToVisual(presenter).TransformPoint(new(0, 0)) == completionBefore,
            "details tabs and completion remain visible and stationary while content scrolls");
        var originalExtent = scroll.ExtentHeight;
        presenter.Width = 600;
        await Wait(() => scroll.ViewportWidth < 570);
        Check(scroll.ExtentWidth <= scroll.ViewportWidth + 1 && scroll.ExtentHeight >= originalExtent,
            "production modal resize wraps description vertically without leaking horizontal extent");
        presenter.WriteLayoutDiagnostics(Path.Combine(Path.GetDirectoryName(path)!, "Native-Details-Geometry.winui-layout.json"));

        static IEnumerable<ViewNode> Walk(ViewNode root)
        {
            yield return root;
            foreach (var child in root.Children)
                foreach (var node in Walk(child)) yield return node;
        }
    }

    private async Task PlayniteDetailsNavigationAsync(string path, JsonElement frameNames)
    {
        var options = new JsonSerializerOptions { PropertyNameCaseInsensitive = true };
        options.Converters.Add(new JsonStringEnumConverter(JsonNamingPolicy.CamelCase));
        presenter.Width = 1000;
        presenter.Height = 650;
        presenter.ApplyAppearance(AppearanceSettings.Default with { Motion = MotionPreference.Reduced }, false);
        var frames = new List<(ViewSnapshot Snapshot, Dictionary<string, BridgeNodeRenderStyles> Styles)>();
        foreach (var name in frameNames.EnumerateArray())
        {
            using var frameFile = JsonDocument.Parse(await File.ReadAllBytesAsync(Path.Combine(Path.GetDirectoryName(path)!, name.GetString()!)));
            frames.Add((SnapshotJson.Deserialize(System.Text.Encoding.UTF8.GetBytes(frameFile.RootElement.GetProperty("snapshot").GetRawText())),
                frameFile.RootElement.GetProperty("renderStyles").Deserialize<Dictionary<string, BridgeNodeRenderStyles>>(options)!));
        }
        long sequence = 0;
        foreach (var anchorAction in new[] { "playnite-library.launch", "playnite-library.details.tab.achievements" })
        {
            Button? anchor = null;
            foreach (var frame in frames)
            {
                var snapshot = frame.Snapshot with { Sequence = ++sequence };
                var descriptor = new BridgeWidgetDescriptor { Id = "playnite.navigation", Name = "Playnite navigation",
                    InstanceId = snapshot.WidgetInstanceId, RuntimeGeneration = "production-fixture", PresentationGeneration = "production-fixture",
                    Icon = WidgetGlyph.Play, PackageContentDigest = string.Empty };
                presenter.Apply(new(new(descriptor.Id, descriptor.RuntimeGeneration, descriptor.PresentationGeneration, 1,
                    descriptor.InstanceId, snapshot.Sequence, snapshot.ActiveInputScopeId), descriptor, snapshot, frame.Styles));
                await Task.Delay(120);
                if (anchor is null)
                {
                    var node = Walk(snapshot.Root).Single(node => node.ActionId == anchorAction);
                    anchor = Find<Button>("Widget." + node.Id)!;
                    Check(anchor.Focus(FocusState.Keyboard), "initial details navigation anchor accepts keyboard/controller focus");
                }
                Check(ReferenceEquals(FocusManager.GetFocusedElement(XamlRoot), anchor),
                    $"native focus survives optional-tab publication {sequence}");
                var guide = presenter.CaptureControllerGuide();
                Check(guide.Any(hint => hint.Button == ControllerButton.LeftBumper) &&
                    guide.Any(hint => hint.Button == ControllerButton.RightBumper),
                    $"both bumper routes remain available after optional-tab publication {sequence}");
            }
        }

        static IEnumerable<ViewNode> Walk(ViewNode root)
        {
            yield return root;
            foreach (var child in root.Children)
                foreach (var node in Walk(child)) yield return node;
        }
    }
