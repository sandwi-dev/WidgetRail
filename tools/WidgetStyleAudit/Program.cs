using System.Globalization;
using System.Text.Json;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using WidgetRail.PlatformSettings;
using WidgetRail.WidgetStyling;

if (args.Length is < 2 or > 3 || args.Length == 3 && args[2] != "--verify")
{
    Console.Error.WriteLine("Usage: WidgetStyleAudit <repository-root> <output-json> [--verify]");
    return 2;
}
var root = Path.GetFullPath(args[0]);
var output = Path.GetFullPath(args[1]);
var catalog = new ThemeCatalog(new PlatformSettingsPaths(Path.Combine(Path.GetTempPath(), "wrail-style-audit")));
var findings = new List<Finding>();
var inventories = new List<Inventory>();
var roots = new[] { "src/FirstPartyWidgets", "samples", "templates", "tests/YtMusicCompanionFixture", "tests/FullApplicationWidgetFixture" };
var sourceFiles = roots.SelectMany(folder => Files(Path.Combine(root, folder), "*.wrss")).Order().ToArray();
if (sourceFiles.Length == 0)
{
    Console.Error.WriteLine("No widget WRSS files found; check the repository root.");
    return 2;
}
var externalSurfaces = roots.SelectMany(folder => Files(Path.Combine(root, folder), "*"))
    .Where(path => Path.GetExtension(path) is ".css" or ".html" or ".xaml").Select(Relative).Order().ToArray();
foreach (var path in sourceFiles)
{
    var relative = Relative(path);
    var widgetRoot = Path.GetDirectoryName(Path.GetDirectoryName(path))!;
    var package = WrssPackageLoader.LoadFile(path, Path.GetDirectoryName(path)!);
    var rules = package.Documents.SelectMany(document => document.Statements).OfType<WrssRule>().ToArray();
    var diagnostics = new List<WrssDiagnostic>(package.Diagnostics.Concat(package.Documents.SelectMany(WinUiStyleDiagnostics.Analyze)));
    var codePaths = relative.StartsWith("templates/", StringComparison.Ordinal)
        ? (Path.GetFileName(path) switch
        {
            "default.wrss" => new[] { "basic", "data", "multipage" },
            "media.wrss" => ["media"], "embedded-media.wrss" => ["embedded-media"], _ => ["webapp"],
        }).Select(profile => Path.Combine(widgetRoot, "profiles", profile + ".cs.template"))
        : Files(widgetRoot, "*.cs");
    var calls = codePaths.SelectMany(ReadCalls).ToArray();
    var probes = calls.ToList();
    // Every authored selector is resolved, even when its class is generated by
    // a helper or a dynamic branch that cannot be tied to a literal UI call.
    foreach (var rule in rules)
    foreach (var selector in rule.Selectors.Where(selector => !selector.IsRoot))
    {
        if (probes.Any(probe => selector.Matches(new(probe.Role, probe.Id, probe.Classes, selector.States)))) continue;
        var role = selector.Role is null or "*" ? "unknown" : selector.Role;
        probes.Add(new(role, selector.Id, selector.Classes.ToHashSet(), Relative(path), rule.Location.Line, [], "selector-only"));
    }
    var unique = probes.DistinctBy(probe => (probe.Source, probe.Line, probe.Role, string.Join(' ', probe.Classes.Order()))).ToArray();
    foreach (var theme in catalog.BuiltInThemes)
    {
        var compiled = ThemeLayerCompiler.Compile(catalog.BuiltInDefault.Package, package, theme.Package);
        diagnostics.AddRange(compiled.Diagnostics);
        if (!compiled.IsValid) continue;
        var resolvedTheme = compiled.Theme!;
        foreach (var probe in unique)
        {
            var normal = Resolve(probe, []);
            var classes = string.Join(' ', probe.Classes.Order());
            if (probe.Kind == "dynamic-call")
                Add("dynamic-classes", "coverage-gap", "A class argument is computed; only literal classes were resolved. Inspect its branches or runtime snapshot.", "normal");
            if (probe.Role == "text" && normal.Get("color") is null && probe.Kind != "dynamic-call")
                Add("missing-text-ink", "native-default-dependent", "No resolved color on an actual UI.Text/RichText call; native inheritance must be verified.", "normal");
            if (probe.Kind == "selector-only")
                Add("unmapped-selector", "coverage-gap", "No literal source UI call was mapped; generated/conditional/helper usage needs review.", "normal");

            foreach (var (stateName, states) in States())
            {
                var style = Resolve(probe, states);
                if (style.Get("color") is { } ink && probe.Role is "text" or "button" or "select" or "textEntry")
                {
                    var ownFill = style.Get("background");
                    var parent = probe.Parents.Select(parent => Resolve(parent, [])).FirstOrDefault(parent => parent.Get("background") is not null);
                    var fill = ownFill ?? parent?.Get("background");
                    if (fill is not null && Color.Try(ink.Text, out var foreground) && foreground.A > 0 && Color.Try(fill.Text, out var background) && background.A >= .90)
                    {
                        var ratio = new[] { new Color(0, 0, 0), new Color(255, 255, 255) }.Min(under =>
                        {
                            var painted = background.Over(under);
                            return Color.Contrast(foreground.Over(painted), painted);
                        });
                        if (ratio < 4.5 && !states.Contains(WrssPseudoState.Disabled))
                            Add("low-text-contrast", "calculated-pair", $"{ink.Text} on {fill.Text}: {ratio:F2}:1 (base fills, no shading/opacity simulation; {(ownFill is null ? "lexical parent" : "same node")}).", stateName);
                    }
                }
                if (probe.Role is "button" or "select" or "slider" or "textEntry" or "actionSurface" && states.Contains(WrssPseudoState.Focused))
                {
                    if (style.Get("outline-color") is { } edge && style.Get("background") is { } fill &&
                        Color.Try(edge.Text, out var edgeColor) && Color.Try(fill.Text, out var fillColor) && fillColor.A >= .90 && edgeColor.A > 0)
                    {
                        var ratio = Color.Contrast(edgeColor.Over(fillColor), fillColor);
                        if (ratio < 3)
                            Add("low-focus-contrast", "calculated-pair", $"{edge.Text} against {fill.Text}: {ratio:F2}:1; native geometry and shading require review.", stateName);
                    }
                }
            }
            void Add(string code, string confidence, string detail, string state) => findings.Add(new(relative, theme.Descriptor.Name,
                probe.Source, probe.Line, probe.Role, classes, code, confidence, state, detail));
            WrssResolvedStyle Resolve(Probe p, WrssPseudoState[] states) => resolvedTheme.Resolve(new(p.Role, p.Id, p.Classes, states.ToHashSet()));
        }
    }
    var literals = rules.SelectMany(rule => rule.Declarations).Where(declaration =>
        (declaration.Property is "color" or "background" || declaration.Property.EndsWith("-color", StringComparison.Ordinal)) &&
        !declaration.Value.Contains("var(", StringComparison.Ordinal)).Select(declaration =>
            new { declaration.Location.Line, declaration.Property, declaration.Value }).ToArray();
    var opacity = rules.SelectMany(rule => rule.Declarations).Where(declaration => declaration.Property is "opacity" or "background-blur" or "surface-shading")
        .Select(declaration => new { declaration.Location.Line, declaration.Property, declaration.Value }).ToArray();
    var tokens = rules.SelectMany(rule => rule.Declarations).Where(declaration => declaration.Property.StartsWith("--", StringComparison.Ordinal))
        .Select(declaration => new { declaration.Location.Line, declaration.Property, declaration.Value }).ToArray();
    inventories.Add(new(relative, rules.Length, rules.Sum(rule => rule.Selectors.Count), calls.Length,
        unique.Count(probe => probe.Kind == "source-call"), unique.Count(probe => probe.Kind == "selector-only"),
        diagnostics.Distinct().ToArray(), literals, opacity, tokens));
}
var grouped = findings.GroupBy(item => new { item.Style, item.Source, item.Line, item.Role, item.Classes, item.Code, item.Confidence, item.Detail })
    .Select(group => new { group.Key, Themes = group.Select(item => item.Theme).Distinct().Order(), States = group.Select(item => item.State).Distinct().Order() }).ToArray();
Directory.CreateDirectory(Path.GetDirectoryName(output)!);
File.WriteAllText(output, JsonSerializer.Serialize(new
{
    Scope = "Repository WRSS and literal UI factory call audit; not native rendering validation. Dynamic classes, helper-generated nodes, runtime layouts, image content and subtree opacity require review.",
    ThemeCount = catalog.BuiltInThemes.Count, Inventories = inventories, ExternalSurfaces = externalSurfaces, Findings = grouped,
}, new JsonSerializerOptions { WriteIndented = true }));
Console.WriteLine($"Audited {inventories.Count} WRSS files against {catalog.BuiltInThemes.Count} themes; {inventories.Sum(item => item.Selectors)} selectors; {grouped.Length} grouped findings.");
foreach (var group in grouped.GroupBy(item => item.Key.Code)) Console.WriteLine($"{group.Key}: {group.Count()}");
Console.WriteLine(output);
var shippingFindings = findings.Where(item => !item.Style.StartsWith("tests/", StringComparison.Ordinal) &&
    item.Code is "missing-text-ink" or "low-text-contrast" or "low-focus-contrast").ToArray();
Console.WriteLine($"Shipping/template calculated-pair or missing-ink findings: {shippingFindings.Length}. Coverage gaps remain review items, not passes.");
return inventories.Any(item => item.Diagnostics.Any(diagnostic => diagnostic.Severity == WrssDiagnosticSeverity.Error)) ||
    args.Length == 3 && shippingFindings.Length > 0 ? 1 : 0;

string Relative(string path) => Path.GetRelativePath(root, path).Replace('\\', '/');
static IEnumerable<string> Files(string directory, string pattern) => Directory.Exists(directory)
    ? Directory.EnumerateFiles(directory, pattern, new EnumerationOptions { RecurseSubdirectories = true, AttributesToSkip = FileAttributes.ReparsePoint })
        .Where(path => !path.Split(Path.DirectorySeparatorChar).Any(part => part is "bin" or "obj" or ".git")) : [];

IEnumerable<Probe> ReadCalls(string path)
{
    var tree = CSharpSyntaxTree.ParseText(File.ReadAllText(path));
    foreach (var invocation in tree.GetRoot().DescendantNodes().OfType<InvocationExpressionSyntax>())
    {
        if (!Factory(invocation, out var role, out var method)) continue;
        var (classes, outer, dynamicClasses) = ClassChain(invocation);
        if (method == "Text" && invocation.ArgumentList.Arguments.FirstOrDefault()?.Expression is LiteralExpressionSyntax content &&
            content.IsKind(SyntaxKind.StringLiteralExpression) && string.IsNullOrWhiteSpace(content.Token.ValueText)) continue;
        var parents = outer.Ancestors().OfType<InvocationExpressionSyntax>().Where(call => Factory(call, out _, out _))
            .Select(call =>
            {
                Factory(call, out var parentRole, out _);
                return new Probe(parentRole, null, ClassChain(call).Classes, Relative(path), call.GetLocation().GetLineSpan().StartLinePosition.Line + 1, [], "source-call");
            }).ToArray();
        var idIndex = method is "Text" or "Icon" or "ActionSurface" ? 1 : method is "Button" or "IconButton" ? 2 : 0;
        var id = invocation.ArgumentList.Arguments.ElementAtOrDefault(idIndex)?.Expression is LiteralExpressionSyntax literal && literal.IsKind(SyntaxKind.StringLiteralExpression)
            ? literal.Token.ValueText : null;
        yield return new(role, id, classes, Relative(path), invocation.GetLocation().GetLineSpan().StartLinePosition.Line + 1, parents, dynamicClasses ? "dynamic-call" : "source-call");
    }
}
static bool Factory(InvocationExpressionSyntax call, out string role, out string method)
{
    role = ""; method = "";
    if (call.Expression is not MemberAccessExpressionSyntax { Expression: IdentifierNameSyntax { Identifier.ValueText: "UI" } } member) return false;
    method = member.Name.Identifier.ValueText;
    role = method switch
    {
        "Text" or "RichText" => "text", "Button" or "IconButton" => "button", "ActionSurface" => "actionSurface",
        "Stack" => "stack", "Row" => "row", "Scroll" => "scroll", "Grid" => "grid", "Icon" => "icon", "Image" => "image",
        "TextEntry" => "textEntry", "Select" => "select", "Slider" => "slider", "Progress" => "progress", _ => "",
    };
    return role.Length > 0;
}
static (HashSet<string> Classes, SyntaxNode Outer, bool DynamicClasses) ClassChain(InvocationExpressionSyntax call)
{
    var classes = new HashSet<string>(StringComparer.Ordinal);
    Factory(call, out _, out var method);
    if (method == "ActionSurface") classes.Add("wrail-action-surface");
    if (method == "IconButton")
    {
        classes.Add("wrail-icon-button");
        foreach (var argument in call.ArgumentList.Arguments)
            if (argument.Expression is MemberAccessExpressionSyntax member && member.Expression.ToString() is "IconButtonVariant" or "IconButtonSize")
                classes.Add("wrail-icon-button--" + member.Name.Identifier.ValueText.ToLowerInvariant());
    }
    SyntaxNode outer = call;
    var dynamicClasses = false;
    while (outer.Parent is MemberAccessExpressionSyntax member && member.Expression == outer && member.Parent is InvocationExpressionSyntax next)
    {
        if (member.Name.Identifier.ValueText is "Classes" or "AddClasses")
            foreach (var arg in next.ArgumentList.Arguments)
                if (arg.Expression is LiteralExpressionSyntax literal && literal.IsKind(SyntaxKind.StringLiteralExpression)) classes.Add(literal.Token.ValueText);
                else dynamicClasses = true;
        outer = next;
    }
    return (classes, outer, dynamicClasses);
}
static IEnumerable<(string, WrssPseudoState[])> States()
{
    yield return ("normal", []);
    yield return ("focused", [WrssPseudoState.Focused]);
    yield return ("selected", [WrssPseudoState.Selected]);
    yield return ("selected-focused", [WrssPseudoState.Selected, WrssPseudoState.Focused]);
    yield return ("pressed", [WrssPseudoState.Focused, WrssPseudoState.Pressed]);
    yield return ("disabled-focused", [WrssPseudoState.Disabled, WrssPseudoState.Focused]);
    yield return ("busy-focused", [WrssPseudoState.Busy, WrssPseudoState.Focused]);
}
record Probe(string Role, string? Id, HashSet<string> Classes, string Source, int Line, Probe[] Parents, string Kind);
record Finding(string Style, string Theme, string Source, int Line, string Role, string Classes, string Code, string Confidence, string State, string Detail);
record Inventory(string Style, int Rules, int Selectors, int SourceCalls, int MappedCalls, int UnmappedSelectors,
    WrssDiagnostic[] Diagnostics, object[] LiteralColors, object[] Compositing, object[] Tokens);
readonly record struct Color(double R, double G, double B, double A = 1)
{
    public Color Over(Color background) => new(R * A + background.R * (1 - A), G * A + background.G * (1 - A), B * A + background.B * (1 - A));
    public static double Contrast(Color a, Color b)
    {
        static double L(Color c)
        {
            static double F(double x) => x / 255 <= .04045 ? x / 255 / 12.92 : Math.Pow((x / 255 + .055) / 1.055, 2.4);
            return .2126 * F(c.R) + .7152 * F(c.G) + .0722 * F(c.B);
        }
        var x = L(a); var y = L(b); return (Math.Max(x, y) + .05) / (Math.Min(x, y) + .05);
    }
    public static bool Try(string value, out Color result)
    {
        result = default;
        if (value == "transparent") { result = new(0, 0, 0, 0); return true; }
        if (value.StartsWith('#'))
        {
            var hex = value[1..]; if (hex.Length is 3 or 4) hex = string.Concat(hex.Select(c => new string(c, 2)));
            if (hex.Length is not (6 or 8)) return false;
            double Byte(int start) => int.Parse(hex.AsSpan(start, 2), NumberStyles.HexNumber, CultureInfo.InvariantCulture);
            result = new(Byte(0), Byte(2), Byte(4), hex.Length == 8 ? Byte(6) / 255 : 1); return true;
        }
        if (!value.StartsWith("rgb", StringComparison.Ordinal)) return false;
        var parts = value[(value.IndexOf('(') + 1)..^1].Split(',').Select(part => double.Parse(part, CultureInfo.InvariantCulture)).ToArray();
        result = new(parts[0], parts[1], parts[2], parts.Length == 4 ? parts[3] : 1); return true;
    }
}
