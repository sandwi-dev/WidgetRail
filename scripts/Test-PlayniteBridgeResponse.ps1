[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$SourceDirectory,
    [Parameter(Mandatory)][string]$OutputDirectory
)
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$repository = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$spec = Get-Content (Join-Path $repository 'samples/PlayniteLibraryWidget/bridge/source.json') -Raw | ConvertFrom-Json
$patch = $spec.patches | Where-Object target -eq 'src/Server/HttpApiServer.cs'
$source = Join-Path (Resolve-Path -LiteralPath $SourceDirectory).Path $patch.target
if ((Get-FileHash -LiteralPath $source).Hash -ne $patch.afterSha256) { throw 'Response fixture requires the exact patched Bridge source.' }
$output = [IO.Path]::GetFullPath($OutputDirectory)
New-Item -ItemType Directory -Force -Path $output | Out-Null
dotnet build (Join-Path $repository 'tests/PlayniteBridgeResponseFixture/PlayniteBridgeResponseFixture.csproj') `
    -c Release -o $output "-p:PlayniteBridgeHttpSource=$source" -p:ImportDirectoryBuildProps=false -p:ImportDirectoryBuildTargets=false `
    "-bl:$output/response-test-{}.binlog" -v:q
if ($LASTEXITCODE -ne 0) { throw 'Bridge response fixture build failed.' }
# Uses only an ephemeral loopback listener, stub routes/auth and generated bytes.
# It neither connects to Playnite nor reads the user's token, library or settings.
$process = Start-Process (Join-Path $output 'PlayniteBridgeResponseFixture.exe') -WindowStyle Hidden -PassThru `
    -RedirectStandardOutput (Join-Path $output 'results.log') -RedirectStandardError (Join-Path $output 'errors.log')
if (!$process.WaitForExit(30000)) {
    Stop-Process -Id $process.Id
    throw 'Bridge response fixture timed out.'
}
Get-Content (Join-Path $output 'results.log')
if ($process.ExitCode -ne 0) {
    Get-Content (Join-Path $output 'errors.log')
    throw 'Bridge response fixture failed.'
}
